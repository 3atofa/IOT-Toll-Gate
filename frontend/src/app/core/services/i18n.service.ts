@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly lang = signal<Lang>(this.readInitial());

  constructor() {
    this.applyDocument(this.lang());
  }

  setLang(lang: Lang): void {
    this.lang.set(lang);
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* ignore */
    }
    this.applyDocument(lang);
  }

  toggle(): void {
    this.setLang(this.lang() === 'en' ? 'ar' : 'en');
  }

  t(key: string): string {
    const dict = DICT[this.lang()];
    return (dict && dict[key]) || DICT.en[key] || key;
  }

  isRtl(): boolean {
    return this.lang() === 'ar';
  }

  private applyDocument(lang: Lang): void {
    if (typeof document === 'undefined') {
      return;
    }
    const html = document.documentElement;
    html.setAttribute('lang', lang);
    html.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  }

  private readInitial(): Lang {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored === 'en' || stored === 'ar') {
        return stored;
      }
    } catch {
      /* ignore */
    }
    return 'en';
  }
}
